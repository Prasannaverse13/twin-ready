from playwright.sync_api import sync_playwright
errs=[]
with sync_playwright() as p:
    b=p.chromium.launch(); ctx=b.new_context(accept_downloads=True); pg=ctx.new_page()
    pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto('http://localhost:4173/index.html')
    pg.click('button[data-act=demo-fill]'); pg.fill('#g-pass','correct horse battery')
    pg.click('button[data-act=create]'); pg.wait_for_selector('button[data-tab=memory]')
    pg.click('button[data-tab=memory]'); pg.click('button[data-act=demo-notes]')
    pg.click('button[data-act=ingest]'); pg.wait_for_function("document.body.innerText.includes('Added')", timeout=20000)
    print('MEM:', pg.locator('text=/Added \\d+ memories/').first.inner_text())
    pg.click('button[data-act=tidy]'); print('TIDY:', pg.locator('text=/Merged \\d+/').first.inner_text())
    for i in range(3): pg.locator('input[data-pub]').nth(i).check()
    pg.click('button[data-tab=public]'); print('GATE:', pg.locator('text=/Publish Gate passed|Gate blocked/').first.inner_text())
    pg.click('button[data-tab=ledger]'); pg.click('button[data-act=red]')
    print('RED:', pg.locator('text=/questions with a fake identity/').first.inner_text())
    pg.click('button[data-tab=setup]')
    with pg.expect_download() as d: pg.click('button[data-act=backup]')
    print('BACKUP:', d.value.suggested_filename)
    pg.click('button[data-tab=talk]'); pg.fill('#q','Should I join Rahul startup or stay?'); pg.click('button[data-act=send]')
    pg.wait_for_timeout(4000)
    print('TALK:', pg.locator('.turn').first.inner_text().replace('\n',' | ')[:300])
    pg.screenshot(path='/tmp/twin-talk.png', full_page=True)
    pg.goto('http://localhost:4173/t.html?id=nothere'); pg.wait_for_timeout(4000)
    print('VISITOR:', pg.inner_text('body')[:120].replace('\n',' | '))
    b.close()
print('PAGE ERRORS:', errs)
